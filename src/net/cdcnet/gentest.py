"""Regenerate the test-only INFs from the release INFs (files only).

CDCTEST.INF (2000 to 7) and CDCT98.INF (98 SE, ME) bind CDCNET to QEMU's
usb-net whole device; RNDTEST.INF binds Windows' own RNDIS driver to it
through CDCRNDIS.INF's sections. Install sections stay identical to the
release INFs; only the models change. None of these is ever released
(ethernet.md section 5.1).
"""
import re
from pathlib import Path

ID = r'USB\VID_0525&PID_A4A2'
here = Path(__file__).resolve().parent
HEAD = ('; SPDX-License-Identifier: GPL-2.0-or-later\n; Copyright (C) 2026 Yeo Kheng Meng\n;\n'
        '; {name} - TEST ONLY, never released; generated by gentest.py from\n'
        '; {source}. {what} QEMU\'s usb-net model, {id},\n'
        '; as a whole device (RNDIS configuration 2 listed first, ECM\n'
        '; configuration 1). ethernet.md section 5.1: a shared gadget VID/PID\n'
        '; never goes in a released INF.\n\n')


def write(name, source, what, body):
    text = HEAD.format(name=name, source=source, what=what, id=ID) + body
    (here / name).write_text(text, newline='\n')


def models_only(text, sections):
    body = text[text.index('[Version]'):]
    block = ''.join('[%s]\n%%Test%%=CDC,%s\n\n' % (s, ID) for s in sections)
    body = re.sub(r'\[Models\].*?(?=\[ControlFlags\])', lambda m: block, body, flags=re.S)
    return body.replace('[Strings]\n', '[Strings]\nTest="CDCNET test: QEMU usb-net (not a release)"\n')


nt = (here / 'CDCNET.INF').read_text()
write('CDCTEST.INF', 'CDCNET.INF', 'Binds CDCNET to',
      models_only(nt, ['Models', 'Models.NTx86.5.1', 'Models.NTamd64']))
nine = (here / 'CDC98.INF').read_text()
write('CDCT98.INF', 'CDC98.INF', 'Binds CDCNET to', models_only(nine, ['Models']))
r = (here / 'CDCRNDIS.INF').read_text()
body = r[r.index('[Version]'):]
body = re.sub(r'(\[Models\.[^\]]+\]\n)(?:%Rndis%=(Rndis\d),[^\n]*\n)+',
              lambda m: m.group(1) + '%Test%=' + m.group(2) + ',' + ID + '\n', body)
body = body.replace('[Strings]\n', '[Strings]\nTest="CDCRNDIS test: QEMU usb-net on the Windows RNDIS driver (not a release)"\n')
write('RNDTEST.INF', 'CDCRNDIS.INF', "Binds Windows' own RNDIS driver to", body)

# RNDIS variants: the same test models with the Protocol value preset to
# 1 (RNDIS only), so a fresh guest exercises QEMU's RNDIS configuration.
for source, name in (('CDCTEST.INF', 'CDCTRND.INF'), ('CDCT98.INF', 'CDC98R.INF')):
    text = (here / source).read_text()
    text = text.replace('; %s - TEST ONLY' % source, '; %s - TEST ONLY (RNDIS preset)' % name)
    text = text.replace('HKR,,Protocol,,0', 'HKR,,Protocol,,1')
    # 98's network setup writes each parameter's default over the AddReg value.
    text = text.replace(r'HKR,Ndi\params\Protocol,default,,0', r'HKR,Ndi\params\Protocol,default,,1')
    text = text.replace('"CDCNET test: QEMU usb-net (not a release)"', '"CDCNET RNDIS test: QEMU usb-net (not a release)"')
    (here / name).write_text(text, newline='\n')
